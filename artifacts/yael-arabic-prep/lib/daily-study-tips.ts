export function getDailyStudyTip(date = new Date()) {
  if (!Number.isFinite(date.getTime())) throw new Error('Invalid study-tip date');
  // Calendar days, not elapsed local hours: DST and month changes must not
  // repeat or skip tips. Every device-local day advances the 30-day cycle.
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  const index = ((day % DAILY_STUDY_TIPS.length) + DAILY_STUDY_TIPS.length) % DAILY_STUDY_TIPS.length;
  return { number: index + 1, text: DAILY_STUDY_TIPS[index] };
}

export function millisecondsUntilNextLocalDay(date = new Date()) {
  const midnight = new Date(date);
  midnight.setHours(24, 0, 0, 0);
  return Math.max(1, midnight.getTime() - date.getTime());
}
