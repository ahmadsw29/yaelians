type Example = { hebrew: string; arabic: string };
type Section = { title: string; body: string; examples: Example[] };
type Quiz = { id: string; prompt: string; options: string[]; correctIndex: number; explanation: string };
export type TeachingLesson = {
  id: string; title: string; summary: string; minutes: number;
  teacher: 'zizo' | 'lumi' | 'nuna' | 'ghaima'; sourceLabel: string; requiresPremium: boolean;
  sections: Section[]; referenceTitle: string; referenceRows: { term: string; meaning: string }[]; quiz: Quiz[];
};
const section = (title: string, body: string, hebrew: string, arabic: string): Section =>
  ({ title, body, examples: [{ hebrew, arabic }] });
const quiz = (id: string, prompt: string, options: string[], correctIndex: number, explanation: string): Quiz =>
  ({ id, prompt, options, correctIndex, explanation });
const pairs = (text: string) => text.split('\n').filter(Boolean).map(line => {
  const [term, meaning] = line.split('|');
  return { term, meaning };
});
const base = (id: string, title: string, summary: string, sourceLabel: string, teacher: TeachingLesson['teacher']) =>
  ({ id, title, summary, sourceLabel, teacher, minutes: 7, requiresPremium: true });

